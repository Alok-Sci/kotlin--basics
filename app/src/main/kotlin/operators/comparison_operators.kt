package operators

/**
 * Comparison Operators
 * These operators compare the values from left operand with the right one, and returns a Boolean value.
 */
fun main(){
    val val1 = 20
    val val2 = 30

    println(val1 == val2) // equal to
    println(val1 != val2) // no equal to
    println(val1 >= val2) // greater than or equal to
    println(val1 <= val2) // less than or equal to
    println(val1 < val2) // less than
    println(val1 > val2) // greater than

}