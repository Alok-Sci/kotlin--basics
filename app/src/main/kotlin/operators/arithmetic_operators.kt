package operators

/**
 * Arithmetic Operators
 * Used to perform arithmetic operations on two numeric values.
 * These operators can work on all standard numeric types:
 *  (Byte, Short, Int, Long, UByte, UShort, UInt, ULong, Float, Double)
 */

fun main(){
    val num1 = 20
    val num2 = 34

    println(num2 + num1) // addition
    println(num2 - num1) // subtraction
    println(num2 * num1) // multiplication
    println(num2 / num1) // division
    println(num2 % num1) // modulo - find remainder
}