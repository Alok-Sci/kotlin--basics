package functions

/**
 * Function
 * It's a reusable block of code designed to perform a specific, isolated task.
 * It's defined using the `fun` keyword and parenthesis `()` at the end of the function name,
 * then a block with `{}` containing all the code.
 *
 * A function is invoked this way `functionName()` to trigger the execution of the code inside of it.
 */

fun greet(){
    println("Hello World")
}

fun main() {
    greet()
}