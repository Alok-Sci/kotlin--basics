package numbers_and_data_types

/**
 * CHAR
 * A Char type can hold a single character, it could be an alphabet, digit, or a symbol.
 * Single quotes ('') are used to enclose the value being assigned.
 */
fun main(){
    val alphabet: Char = 'A'
    val symbol: Char = '#'

    println(alphabet)
    println(symbol)
}