package conditionals

/**
 * If-Else Conditionals
 * Used to check a boolean expression and
 * - execute a set of operations inside if block if/when the condition passes,
 * - execute another set of operations inside else block if/when the condition fails
 */

fun main(){
    val isAdult = true

    if(isAdult){
        println("You are an adult.")
    } else {
        println("You are under age.")
    }
}